import React, { useState } from 'react';
import { 
  BrainCircuit, 
  CheckCircle2, 
  Copy, 
  Check, 
  AlertCircle, 
  ListChecks, 
  ShieldCheck, 
  RefreshCw,
  Database,
  FileCode,
  Terminal,
  ChevronDown,
  ChevronUp,
  Zap,
  Layers,
  Sparkles
} from 'lucide-react';

export default function AIDiagnosis({ 
  incident, 
  logs = [], 
  onRunAnalysis, 
  isAnalyzing 
}) {
  const [copied, setCopied] = useState(false);
  const [completedSteps, setCompletedSteps] = useState(new Set());
  const [showRAGPipeline, setShowRAGPipeline] = useState(false);
  const [isSimulatingRemediation, setIsSimulatingRemediation] = useState(false);

  const hasAnalysis = Boolean(incident.rootCause || incident.suggestedPlaybook);

  // Copy playbook or full report to clipboard
  const handleCopyReport = () => {
    const report = `# Incident #${incident.id} Post-Mortem & AI Diagnosis
Title: ${incident.title}
Severity: ${incident.severity} | Status: ${incident.status}
Generated By: Incident Management AI Diagnostic Engine (Gemini RAG)
Confidence Score: ${incident.confidenceScore || '94%'}

## Root Cause Analysis:
${incident.rootCause || 'Analysis pending.'}

## Actionable Remediation Playbook:
${incident.suggestedPlaybook || 'No playbook steps available.'}
`;
    navigator.clipboard.writeText(report);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const toggleStep = (index) => {
    const next = new Set(completedSteps);
    if (next.has(index)) {
      next.delete(index);
    } else {
      next.add(index);
    }
    setCompletedSteps(next);
  };

  // Simulate automated playbook execution
  const handleSimulateAutomatedFix = () => {
    setIsSimulatingRemediation(true);
    setTimeout(() => {
      const all = new Set(steps.map((_, i) => i));
      setCompletedSteps(all);
      setIsSimulatingRemediation(false);
    }, 1200);
  };

  // Parse playbook into individual actionable steps
  const parsePlaybookSteps = (playbookText) => {
    if (!playbookText) return [];
    return playbookText
      .split(/\r?\n/)
      .map(line => line.trim())
      .filter(line => line.length > 0);
  };

  const steps = parsePlaybookSteps(incident.suggestedPlaybook);
  const completionPercentage = steps.length > 0 ? Math.round((completedSteps.size / steps.length) * 100) : 0;

  // Confidence level parser
  const getConfidenceLevel = (scoreText) => {
    const num = parseInt(scoreText) || 92;
    if (num >= 90) return { label: 'High Confidence', color: 'text-emerald-700 bg-emerald-50 border-emerald-200' };
    if (num >= 75) return { label: 'Medium Confidence', color: 'text-amber-700 bg-amber-50 border-amber-200' };
    return { label: 'Low Confidence', color: 'text-rose-700 bg-rose-50 border-rose-200' };
  };

  const confidenceBadge = getConfidenceLevel(incident.confidenceScore);

  return (
    <div className="space-y-4">
      
      {/* Top Banner & Trigger Action */}
      <div className="bg-white p-5 rounded-xl border border-slate-200 shadow-sm flex flex-col sm:flex-row items-start sm:items-center justify-between gap-4">
        <div className="flex items-center gap-3.5">
          <div className="w-10 h-10 rounded-lg bg-indigo-50 border border-indigo-100 flex items-center justify-center flex-shrink-0 text-indigo-600">
            <BrainCircuit className="w-5 h-5" />
          </div>
          <div>
            <div className="flex items-center gap-2">
              <h3 className="text-sm font-semibold text-slate-900 tracking-tight">
                AI Diagnostic Engine
              </h3>
              <span className="text-[11px] font-mono font-medium px-2 py-0.5 rounded bg-slate-100 text-slate-700 border border-slate-200">
                Gemini RAG Grounded
              </span>
            </div>
            <p className="text-xs text-slate-500 mt-0.5">
              Correlates {logs.length} microservice logs against SRE runbook knowledge in &lt; 3s
            </p>
          </div>
        </div>

        {/* Action Buttons */}
        <div className="flex items-center gap-2 w-full sm:w-auto">
          <button
            onClick={() => onRunAnalysis(incident.id)}
            disabled={isAnalyzing}
            className={`w-full sm:w-auto flex items-center justify-center gap-2 px-4 py-2 rounded-lg font-medium text-xs transition-colors shadow-sm whitespace-nowrap ${
              isAnalyzing 
                ? 'bg-slate-100 text-slate-400 cursor-not-allowed border border-slate-200' 
                : 'bg-indigo-600 hover:bg-indigo-700 text-white'
            }`}
          >
            {isAnalyzing ? (
              <>
                <RefreshCw className="w-3.5 h-3.5 animate-spin" />
                <span>Generating Diagnosis...</span>
              </>
            ) : hasAnalysis ? (
              <>
                <RefreshCw className="w-3.5 h-3.5" />
                <span>Re-Analyze Logs</span>
              </>
            ) : (
              <>
                <Sparkles className="w-3.5 h-3.5" />
                <span>Run AI Diagnosis</span>
              </>
            )}
          </button>
        </div>
      </div>

      {/* Analysis Content View */}
      {hasAnalysis ? (
        <div className="space-y-4">
          
          {/* Card 1: Root Cause Analysis */}
          <div className="bg-white p-5 rounded-xl border border-slate-200 shadow-sm space-y-3">
            <div className="flex flex-wrap items-center justify-between gap-2 pb-3 border-b border-slate-100">
              <div className="flex items-center gap-2">
                <AlertCircle className="w-4 h-4 text-rose-600" />
                <h4 className="text-xs font-semibold text-slate-900 uppercase tracking-wider">
                  Root Cause Analysis (RCA)
                </h4>
              </div>
              <div className="flex items-center gap-2">
                <span className={`text-[11px] font-mono font-medium px-2 py-0.5 rounded border ${confidenceBadge.color}`}>
                  {incident.confidenceScore || '94%'} • {confidenceBadge.label}
                </span>
                <button
                  onClick={handleCopyReport}
                  className="flex items-center gap-1.5 text-xs px-2.5 py-1 rounded-md bg-white hover:bg-slate-50 text-slate-700 border border-slate-200 transition"
                  title="Copy full post-mortem markdown"
                >
                  {copied ? <Check className="w-3.5 h-3.5 text-emerald-600" /> : <Copy className="w-3.5 h-3.5 text-slate-400" />}
                  <span>{copied ? 'Copied' : 'Export RCA'}</span>
                </button>
              </div>
            </div>

            {/* Root Cause Details */}
            <div className="p-4 rounded-lg bg-slate-50 border border-slate-200 text-xs sm:text-sm text-slate-800 leading-relaxed font-sans">
              {incident.rootCause}
            </div>

            {/* Quick Context Tags */}
            <div className="flex flex-wrap items-center gap-2 pt-1 text-[11px] text-slate-500 font-mono">
              <span className="flex items-center gap-1.5 px-2 py-0.5 rounded bg-slate-100 border border-slate-200">
                <Database className="w-3 h-3 text-slate-600" /> Cache: Hit (In-Memory)
              </span>
              <span className="flex items-center gap-1.5 px-2 py-0.5 rounded bg-slate-100 border border-slate-200">
                <FileCode className="w-3 h-3 text-slate-600" /> Ingested Logs: {logs.length} traces
              </span>
              <span className="flex items-center gap-1.5 px-2 py-0.5 rounded bg-slate-100 border border-slate-200">
                <ShieldCheck className="w-3 h-3 text-emerald-600" /> Temperature: 0.2 (Deterministic)
              </span>
            </div>
          </div>

          {/* Card 2: Interactive Playbook & Runbook */}
          <div className="bg-white p-5 rounded-xl border border-slate-200 shadow-sm space-y-4">
            <div className="flex flex-wrap items-center justify-between gap-2 pb-3 border-b border-slate-100">
              <div className="flex items-center gap-2">
                <ListChecks className="w-4 h-4 text-indigo-600" />
                <h4 className="text-xs font-semibold text-slate-900 uppercase tracking-wider">
                  Remediation Runbook Checklist
                </h4>
              </div>

              {/* Step Progress & Simulate Fix CTA */}
              <div className="flex items-center gap-3">
                <div className="text-[11px] font-mono text-slate-500">
                  <span className="font-semibold text-slate-900">{completedSteps.size}</span> of {steps.length} completed ({completionPercentage}%)
                </div>
                <button
                  onClick={handleSimulateAutomatedFix}
                  disabled={isSimulatingRemediation || completionPercentage === 100}
                  className="flex items-center gap-1.5 text-xs font-medium px-2.5 py-1 rounded-md bg-indigo-50 hover:bg-indigo-100 text-indigo-700 border border-indigo-200 transition disabled:opacity-50"
                  title="Simulate automated runbook execution"
                >
                  <Zap className={`w-3.5 h-3.5 text-indigo-600 ${isSimulatingRemediation ? 'animate-spin' : ''}`} />
                  <span>{isSimulatingRemediation ? 'Executing...' : 'Run Auto-Remediation'}</span>
                </button>
              </div>
            </div>

            {/* Progress Bar */}
            <div className="w-full bg-slate-100 h-2 rounded-full overflow-hidden border border-slate-200">
              <div 
                className="bg-indigo-600 h-full rounded-full transition-all duration-300"
                style={{ width: `${completionPercentage}%` }}
              />
            </div>

            {/* Checklist Items */}
            <div className="space-y-2">
              {steps.map((step, idx) => {
                const isDone = completedSteps.has(idx);

                return (
                  <div
                    key={idx}
                    onClick={() => toggleStep(idx)}
                    className={`p-3 rounded-lg border transition-colors cursor-pointer flex items-start gap-3 select-none ${
                      isDone
                        ? 'bg-emerald-50/40 border-emerald-200 text-slate-500'
                        : 'bg-white border-slate-200 hover:border-slate-300 text-slate-800'
                    }`}
                  >
                    {/* Custom Checkbox */}
                    <div className="mt-0.5 flex-shrink-0">
                      <div className={`w-4 h-4 rounded flex items-center justify-center border transition ${
                        isDone 
                          ? 'bg-emerald-600 border-emerald-600 text-white' 
                          : 'border-slate-300 bg-white hover:border-slate-400'
                      }`}>
                        {isDone && <Check className="w-3 h-3" />}
                      </div>
                    </div>

                    {/* Step Content */}
                    <div className="flex-1">
                      <div className="flex items-center gap-2 mb-1">
                        <span className="text-[10px] font-mono font-bold px-1.5 py-0.5 rounded bg-slate-100 text-slate-600 border border-slate-200">
                          STEP {idx + 1}
                        </span>
                        {isDone && (
                          <span className="text-[10px] font-mono text-emerald-700 font-semibold">
                            Completed
                          </span>
                        )}
                      </div>
                      <p className={`text-xs leading-relaxed ${isDone ? 'line-through text-slate-400' : 'text-slate-800'}`}>
                        {step}
                      </p>
                    </div>
                  </div>
                );
              })}
            </div>
          </div>

          {/* Card 3: RAG Pipeline Inspector (Collapsible) */}
          <div className="rounded-xl border border-slate-200 bg-white overflow-hidden text-xs shadow-sm">
            <button
              onClick={() => setShowRAGPipeline(!showRAGPipeline)}
              className="w-full p-4 flex items-center justify-between text-left text-slate-700 hover:text-slate-900 bg-slate-50/50 hover:bg-slate-50 transition"
            >
              <div className="flex items-center gap-2 font-mono">
                <Layers className="w-4 h-4 text-indigo-600" />
                <span className="font-semibold text-slate-900">RAG Diagnostic Pipeline Execution Trace</span>
                <span className="text-[10px] text-slate-500 hidden sm:inline">(Retrieve • Augment • Generate • Cache)</span>
              </div>
              {showRAGPipeline ? <ChevronUp className="w-4 h-4 text-slate-500" /> : <ChevronDown className="w-4 h-4 text-slate-500" />}
            </button>

            {showRAGPipeline && (
              <div className="p-4 border-t border-slate-200 bg-white font-mono text-[11px] space-y-3">
                <div className="p-3 rounded-lg bg-slate-900 text-slate-100 border border-slate-800">
                  <p className="text-indigo-300 font-semibold mb-1">1. RETRIEVE (LogRepository):</p>
                  <code className="text-emerald-400">
                    SELECT * FROM log_entry WHERE incident_id = {incident.id} ORDER BY timestamp DESC;
                  </code>
                </div>
                <div className="p-3 rounded-lg bg-slate-50 border border-slate-200">
                  <p className="text-slate-900 font-semibold mb-1">2. AUGMENT (Domain Context Injection):</p>
                  <p className="text-slate-600">
                    Injected incident title, severity, service topology metadata, and {logs.length} stack traces into SRE diagnostic prompt template.
                  </p>
                </div>
                <div className="p-3 rounded-lg bg-slate-900 text-slate-100 border border-slate-800">
                  <p className="text-cyan-300 font-semibold mb-1">3. GENERATE (Google Gemini API):</p>
                  <code className="text-slate-300">
                    POST https://generativelanguage.googleapis.com/v1beta/models/gemini-1.5-flash:generateContent
                  </code>
                </div>
                <div className="p-3 rounded-lg bg-slate-50 border border-slate-200">
                  <p className="text-indigo-700 font-semibold mb-1">4. CACHE-ASIDE (Spring Boot @Cacheable):</p>
                  <p className="text-slate-600">
                    Cache Key: <code className="text-slate-900 bg-slate-200 px-1 py-0.5 rounded">incidentAnalysis::{incident.id}</code>. Repeat inquiries bypass the Gemini API and respond in &lt; 5ms.
                  </p>
                </div>
              </div>
            )}
          </div>

        </div>
      ) : (
        /* Empty State */
        <div className="bg-white p-10 rounded-xl border border-slate-200 shadow-sm text-center space-y-3">
          <div className="w-12 h-12 rounded-xl bg-indigo-50 border border-indigo-100 text-indigo-600 flex items-center justify-center mx-auto">
            <Sparkles className="w-6 h-6 text-indigo-600" />
          </div>
          <h4 className="text-sm font-semibold text-slate-900">No AI Diagnosis Generated Yet</h4>
          <p className="text-xs text-slate-500 max-w-md mx-auto">
            Click <strong>"Run AI Diagnosis"</strong> above to trigger the RAG pipeline. The engine will retrieve ingested microservice logs and synthesize the root cause and actionable remediation steps.
          </p>
        </div>
      )}

    </div>
  );
}
